constexpr std::int64_t kIssuedOffsets[] = {-4000, -1000, -100, 0, 0, 0, 100, 5000};

std::uint32_t small_percent(SplitMix64& rng) {
  return static_cast<std::uint32_t>(rng.below(101));
}

scp::ReadinessLevel random_readiness(SplitMix64& rng) {
  return static_cast<scp::ReadinessLevel>(rng.below(5));
}

scp::Severity random_severity(SplitMix64& rng) {
  return static_cast<scp::Severity>(rng.below(5));
}

scp::EvidenceBody random_body(EvidenceKind kind, std::uint64_t generation, SplitMix64& rng) {
  switch (kind) {
    case EvidenceKind::FacilityState: {
      scp::FacilityStateEvidence body;
      body.generation = scp::FacilityStateGeneration(generation);
      body.worst_active_severity = random_severity(rng);
      body.active_incidents = static_cast<std::uint32_t>(rng.below(4));
      body.degraded_operation = rng.coin();
      body.emergency_declared = rng.below(8) == 0;
      return body;
    }
    case EvidenceKind::Lifecycle: {
      scp::LifecycleEvidence body;
      body.state = static_cast<scp::LifecycleState>(1 + rng.below(8));
      body.entered_at = scp_test::instant_after(-100);
      body.transition_in_progress = rng.coin();
      return body;
    }
    case EvidenceKind::Capacity: {
      scp::CapacityEvidence body;
      body.snapshot = scp::SnapshotId(0xC0FFEE0000000001ULL, rng.next());
      body.generation = scp::CapacityGeneration(generation);
      body.total_units = rng.below(3) == 0 ? 0 : 100;
      body.committed_units = rng.below(101);
      body.available_units = rng.below(101);
      body.oversubscribed = rng.below(8) == 0;
      return body;
    }
    case EvidenceKind::PowerReadiness:
    case EvidenceKind::CoolingReadiness: {
      scp::ReadinessEvidence body;
      body.snapshot = scp::SnapshotId(0xC0FFEE0000000002ULL, rng.next());
      body.readiness = random_readiness(rng);
      body.headroom_milli_kw = rng.below(10000000);
      body.available_domains = static_cast<std::uint32_t>(rng.below(4));
      body.required_domains = static_cast<std::uint32_t>(rng.below(4));
      return body;
    }
    case EvidenceKind::Policy: {
      scp::PolicyEvidence body;
      body.generation = scp::PolicyGeneration(generation);
      body.rule_count = static_cast<std::uint32_t>(rng.below(8));
      return body;
    }
    case EvidenceKind::Incident: {
      scp::IncidentEvidence body;
      body.active_incidents = static_cast<std::uint32_t>(rng.below(4));
      body.worst_active_severity = random_severity(rng);
      body.emergency_declared = rng.below(8) == 0;
      body.earliest_active = scp_test::instant_after(-100);
      body.suppressed_incidents = static_cast<std::uint32_t>(rng.below(3));
      return body;
    }
    case EvidenceKind::Maintenance: {
      scp::MaintenanceEvidence body;
      body.mode = static_cast<scp::MaintenanceMode>(rng.below(4));
      body.active_windows = static_cast<std::uint32_t>(rng.below(3));
      body.scheduled_windows = static_cast<std::uint32_t>(rng.below(3));
      body.next_window_start = scp_test::instant_after(600);
      body.drain_in_progress = rng.coin();
      body.drained_percent = small_percent(rng);
      return body;
    }
    case EvidenceKind::AsiCapability:
    case EvidenceKind::DfiCapability: {
      scp::CapabilityEvidence body;
      body.readiness = random_readiness(rng);
      const std::uint32_t total = static_cast<std::uint32_t>(rng.below(5));
      body.total_domains = total;
      body.ready_domains = static_cast<std::uint32_t>(rng.below(static_cast<std::uint64_t>(total) + 1ULL));
      body.ready_units = rng.below(1024);
      return body;
    }
    case EvidenceKind::ServiceClass: {
      constexpr std::string_view kClassNames[] = {"interactive-inference", "batch-queue",
                                                  "control-plane"};
      scp::ServiceClassEvidence body;
      const std::uint64_t count = rng.below(3);
      body.class_count = static_cast<std::uint32_t>(count);
      for (std::uint64_t index = 0; index < count; ++index) {
        const std::string_view name_text = kClassNames[rng.below(3)];
        const Result<scp::Name> parsed = scp::Name::parse(name_text);
        if (!parsed.has_value()) {
          continue;
        }
        scp::ServiceClassObligation obligation;
        obligation.service_class = parsed.value();
        obligation.protected_class = rng.coin();
        obligation.minimum_ready_units = static_cast<std::uint32_t>(rng.below(64));
        obligation.minimum_readiness_percent = small_percent(rng);
        body.obligations.push_back(obligation);
      }
      return body;
    }
  }
  return scp::FacilityStateEvidence{};
}

Result<EvidenceRecord> random_record(EvidenceKind kind, std::uint64_t epoch,
                                     std::uint64_t generation, std::uint64_t sequence,
                                     std::uint64_t instance, Timestamp issued_at,
                                     Timestamp valid_until, scp::EvidenceOrigin origin,
                                     SplitMix64& rng) {
  scp::Provenance provenance;
  provenance.authority = scp::owner_of(kind);
  provenance.instance = scp_test::instance_for(instance);
  provenance.epoch = scp::Epoch(epoch);
  provenance.generation = scp::SourceGeneration(generation);
  provenance.sequence = scp::Sequence(sequence);
  provenance.issued_at = issued_at;
  provenance.valid_until = valid_until;
  Result<EvidenceRecord> record =
      EvidenceRecord::create(provenance, kind, random_body(kind, generation, rng));
  if (!record.has_value()) {
    return record.status();
  }
  record.value().origin = origin;
  return record;
}

std::vector<EvidenceRecord> random_evidence_set(SplitMix64& rng, Timestamp evaluation) {
  (void)evaluation;
  std::vector<EvidenceRecord> records;
  for (std::uint16_t raw = 1; raw <= static_cast<std::uint16_t>(scp::kEvidenceKindCount); ++raw) {
    const EvidenceKind kind = static_cast<EvidenceKind>(raw);
    const std::uint64_t count = rng.below(4);
    for (std::uint64_t index = 0; index < count; ++index) {
      const std::uint64_t epoch = 1 + rng.below(3);
      const std::uint64_t generation = 1 + rng.below(4);
      const std::uint64_t sequence = 1 + rng.below(3);
      const std::uint64_t instance = 1 + rng.below(4);
      const std::size_t offset_index =
          static_cast<std::size_t>(rng.below(sizeof(kIssuedOffsets) / sizeof(kIssuedOffsets[0])));
      const Timestamp issued_at = scp_test::instant_after(kIssuedOffsets[offset_index]);
      Timestamp valid_until{};
      const std::uint64_t expiry = rng.below(5);
      if (expiry == 1) {
        valid_until = scp_test::instant_after(-10);
      } else if (expiry == 2) {
        valid_until = scp_test::instant_after(600);
      }
      scp::EvidenceOrigin origin = scp::EvidenceOrigin::Ingested;
      if (rng.below(4) == 0) {
        origin = scp::EvidenceOrigin::RecoveredFromJournal;
      } else if (rng.below(4) == 0) {
        origin = scp::EvidenceOrigin::Revalidated;
      }
      const Result<EvidenceRecord> record = random_record(kind, epoch, generation, sequence,
                                                          instance, issued_at, valid_until, origin,
                                                          rng);
      if (record.has_value()) {
        records.push_back(record.value());
      }
    }
  }
  return records;
}

std::vector<EvidenceRecord> shuffled_records(const std::vector<EvidenceRecord>& records,
                                             SplitMix64& rng) {
  std::vector<EvidenceRecord> shuffled = records;
  if (shuffled.size() > 1) {
    for (std::size_t index = shuffled.size() - 1; index > 0; --index) {
      const std::size_t other = static_cast<std::size_t>(
          rng.below(static_cast<std::uint64_t>(index) + 1ULL));
      std::swap(shuffled[index], shuffled[other]);
    }
  }
  return shuffled;
}

constexpr std::string_view kRuleIds[] = {"rule-a", "rule-b", "rule-c"};
constexpr std::string_view kMetrics[] = {
    scp::kMetricCapacityHeadroomPercent, scp::kMetricAvailableCapacityUnits,
    scp::kMetricPowerHeadroomMilliKw,    scp::kMetricCoolingHeadroomMilliKw,
    scp::kMetricPowerRedundancyAvailable, scp::kMetricCoolingRedundancyAvailable,
    scp::kMetricReadinessPercent,        scp::kMetricAsiReadinessPercent,
    scp::kMetricDfiReadinessPercent,     scp::kMetricActiveIncidents,
    scp::kMetricActiveMaintenanceWindows, scp::kMetricDrainedPercent};

scp::SitePolicy random_policy(SplitMix64& rng, std::size_t rule_count) {
  scp::SitePolicy policy = scp_test::strict_policy();
  policy.generation = scp::PolicyGeneration(1 + rng.below(4));
  policy.freshness.stale_after = scp::seconds(static_cast<std::int64_t>(rng.below(2000)));
  const std::int64_t stale_seconds = policy.freshness.stale_after.nanos / scp::kNanosPerSecond;
  policy.freshness.expire_after =
      scp::seconds(stale_seconds + static_cast<std::int64_t>(rng.below(4000)));
  policy.capacity_headroom_constrained_percent = small_percent(rng);
  policy.capacity_headroom_degraded_percent =
      static_cast<std::uint32_t>(rng.below(static_cast<std::uint64_t>(
                                     policy.capacity_headroom_constrained_percent) +
                                 1ULL));
  policy.domain_readiness_degraded_percent = small_percent(rng);
  policy.domain_readiness_unavailable_percent = static_cast<std::uint32_t>(
      rng.below(static_cast<std::uint64_t>(policy.domain_readiness_degraded_percent) + 1ULL));
  policy.required_redundancy_domains = static_cast<std::uint32_t>(rng.below(3));
  policy.maintenance_minimum_readiness_percent = small_percent(rng);
  policy.recovery_minimum_drained_percent = small_percent(rng);
  policy.return_to_service_minimum_readiness_percent = small_percent(rng);
  policy.max_constraints = static_cast<std::size_t>(1 + rng.below(24));
  policy.require_complete_evidence_for_new_obligations = rng.coin();
  policy.require_fresh_evidence_for_new_obligations = rng.coin();
  policy.require_unconflicted_evidence_for_new_obligations = rng.coin();
  for (std::size_t index = 0; index < rule_count; ++index) {
    scp::ThresholdRule rule;
    const Result<scp::Name> rule_id = scp::Name::parse(kRuleIds[rng.below(3)]);
    if (!rule_id.has_value()) {
      continue;
    }
    rule.rule_id = rule_id.value();
    rule.kind = scp::ConstraintKind::CapacityHeadroomLow;
    rule.severity = random_severity(rng);
    rule.comparison = static_cast<scp::Comparison>(1 + rng.below(4));
    rule.threshold = rng.below(101);
    rule.blocking = rng.coin();
    rule.subject = std::string(kMetrics[rng.below(sizeof(kMetrics) / sizeof(kMetrics[0]))]);
    policy.rules.push_back(rule);
  }
  return policy;
}

