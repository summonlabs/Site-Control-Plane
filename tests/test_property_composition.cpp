SCP_TEST(a_gate_that_is_open_does_not_close_when_readiness_only_improves) {
  const Timestamp evaluation = scp_test::base_instant();
  const scp::SitePolicy policy = scp_test::strict_policy();
  constexpr scp::GateKind kGates[] = {
      scp::GateKind::NewObligation,  scp::GateKind::MaintenanceEntry,
      scp::GateKind::ControlledDrain, scp::GateKind::EmergencyOperation,
      scp::GateKind::RecoveryStart,  scp::GateKind::ReturnToService};
  constexpr EvidenceKind kDomains[] = {EvidenceKind::PowerReadiness,
                                       EvidenceKind::CoolingReadiness,
                                       EvidenceKind::AsiCapability,
                                       EvidenceKind::DfiCapability};
  std::size_t pairs = 0;
  for (std::uint64_t scenario = 0; scenario < kScenarioCount; ++scenario) {
    const std::uint64_t seed = kMasterSeed * 17ULL + scenario * kSeedStride;
    SplitMix64 rng(seed);
    const std::vector<EvidenceRecord> records = random_evidence_set(rng, evaluation);
    const Result<SiteStateSnapshot> before =
        scp::compose_site_state(records, options_for(evaluation, policy));
    if (!before.has_value()) {
      continue;
    }
    const EvidenceKind domain = kDomains[scenario % 4];
    const scp::EvidenceSlot slot{scp::owner_of(domain), domain};
    const SlotResolution* previous = before.value().find_slot(slot);
    const std::uint64_t epoch =
        (previous == nullptr || previous->accepted_epoch.is_unset()) ? 1ULL
                                                                    : previous->accepted_epoch.value();
    const std::uint64_t generation =
        (previous == nullptr ? 0ULL : previous->accepted_generation.value()) + 1ULL;

    scp::Provenance provenance;
    provenance.authority = scp::owner_of(domain);
    provenance.instance = scp_test::instance_for(21);
    provenance.epoch = scp::Epoch(epoch);
    provenance.generation = scp::SourceGeneration(generation);
    provenance.sequence = scp::Sequence(1);
    provenance.issued_at = evaluation;
    Result<EvidenceRecord> upgraded = [&]() -> Result<EvidenceRecord> {
      if (domain == EvidenceKind::PowerReadiness || domain == EvidenceKind::CoolingReadiness) {
        scp::ReadinessEvidence body;
        body.snapshot = scp::SnapshotId(0xC0FFEE0000000009ULL, 0x0000000000000009ULL);
        body.readiness = scp::ReadinessLevel::Ready;
        body.headroom_milli_kw = 5000000;
        body.available_domains = 2;
        body.required_domains = 2;
        return EvidenceRecord::create(provenance, domain, body);
      }
      scp::CapabilityEvidence body;
      body.readiness = scp::ReadinessLevel::Ready;
      body.ready_domains = 8;
      body.total_domains = 8;
      body.ready_units = 512;
      return EvidenceRecord::create(provenance, domain, body);
    }();
    if (!upgraded.has_value()) {
      continue;
    }
    std::vector<EvidenceRecord> augmented = records;
    augmented.push_back(upgraded.value());
    const Result<SiteStateSnapshot> after =
        scp::compose_site_state(augmented, options_for(evaluation, policy));
    if (!after.has_value()) {
      check_scenario(false, "the improved evidence set composes",
                     "compose reported " + after.status().to_string(), seed, augmented);
      continue;
    }
    ++pairs;

    // The scope of the property: every other slot resolves to exactly what it
    // resolved to before, and observed readiness did not fall.
    bool other_slots_unchanged = true;
    for (const SlotResolution& resolution : before.value().slots) {
      if (resolution.slot == slot) {
        continue;
      }
      const SlotResolution* after_resolution = after.value().find_slot(resolution.slot);
      if (after_resolution == nullptr ||
          !(after_resolution->accepted_id == resolution.accepted_id) ||
          after_resolution->outcome != resolution.outcome) {
        other_slots_unchanged = false;
      }
    }
    check_scenario(other_slots_unchanged,
                   "upgrading one dependency domain leaves every other slot resolved the same",
                   "another slot changed", seed, augmented);
    check_scenario(after.value().readiness_percent >= before.value().readiness_percent,
                   "readiness never falls when a domain is upgraded to ready",
                   "before=" + std::to_string(before.value().readiness_percent) + " after=" +
                       std::to_string(after.value().readiness_percent),
                   seed, augmented);
    const SlotResolution* upgraded_slot = after.value().find_slot(slot);
    check_scenario(upgraded_slot != nullptr && upgraded_slot->accepted_id == upgraded.value().id,
                   "the upgraded publication is accepted for its slot",
                   "the upgrade was not accepted", seed, augmented);

    for (const scp::GateKind kind : kGates) {
      const Result<scp::ReadinessGate> before_gate =
          scp::evaluate_gate(kind, before.value(), policy);
      const Result<scp::ReadinessGate> after_gate = scp::evaluate_gate(kind, after.value(), policy);
      if (!before_gate.has_value() || !after_gate.has_value()) {
        check_scenario(false, "every gate evaluates on both snapshots",
                       std::string("gate ") + std::string(scp::to_string(kind)) + " failed to evaluate",
                       seed, augmented);
        continue;
      }
      const bool monotone = !before_gate.value().open || after_gate.value().open;
      check_scenario(monotone,
                     "no gate that was open becomes closed when readiness only improves",
                     std::string("gate ") + std::string(scp::to_string(kind)) +
                         " was open before and is closed after",
                     seed, augmented);
    }
  }
  SCP_CHECK(pairs > 100);
}

SCP_TEST(the_reported_reduction_buckets_account_for_every_record) {
  const Timestamp evaluation = scp_test::base_instant();
  const scp::SitePolicy policy = scp_test::strict_policy();

  // Two generations of a healthy site: 22 distinct identities, 11 of which lose.
  std::vector<EvidenceRecord> two_generations = scp_test::healthy_site_records(evaluation, 5);
  append(two_generations, scp_test::healthy_site_records(evaluation, 2));
  two_generations.push_back(two_generations.front());
  two_generations.push_back(two_generations.at(7));
  const Result<scp::ReductionResult> reduction =
      scp::reduce_evidence(two_generations, policy, evaluation);
  SCP_REQUIRE_OK(reduction);
  SCP_CHECK_EQ(reduction.value().duplicates_merged, std::size_t{2});
  SCP_CHECK_EQ(reduction.value().accepted.size(), scp::kEvidenceKindCount);
  check_reduction_partition(two_generations, reduction.value(), 101);

  // The same identity, with records the runtime refuses to accept at all.
  std::vector<EvidenceRecord> mixed = two_generations;
  const EvidenceRecord* facility = nullptr;
  for (const EvidenceRecord& record : two_generations) {
    if (record.kind == EvidenceKind::FacilityState) {
      facility = &record;
      break;
    }
  }
  SCP_REQUIRE(facility != nullptr);
  EvidenceRecord forged = *facility;
  forged.provenance.authority = SourceAuthority::FacilityCapacity;
  const Result<scp::EvidenceId> forged_id = scp::derive_evidence_id(
      forged.provenance, forged.kind, forged.schema_version, forged.body);
  SCP_REQUIRE_OK(forged_id);
  forged.id = forged_id.value();
  mixed.push_back(forged);

  EvidenceRecord identityless = *facility;
  identityless.id = scp::EvidenceId{};
  mixed.push_back(identityless);

  const Result<scp::ReductionResult> mixed_reduction = scp::reduce_evidence(mixed, policy,
                                                                           evaluation);
  SCP_REQUIRE_OK(mixed_reduction);
  SCP_CHECK_EQ(mixed_reduction.value().unauthorized_count, std::size_t{1});
  SCP_CHECK_EQ(distinct_rejected_count(mixed_reduction.value()), std::size_t{2});
  check_reduction_partition(mixed, mixed_reduction.value(), 102);
}

