std::uint64_t pick_extreme(SplitMix64& rng, std::uint64_t normal) {
  switch (rng.below(6)) {
    case 0: return 0;
    case 1: return std::numeric_limits<std::uint64_t>::max();
    case 2: return 1;
    case 3: return rng.next();
    default: return normal;
  }
}

std::int64_t pick_extreme_time(SplitMix64& rng) {
  switch (rng.below(6)) {
    case 0: return 0;
    case 1: return std::numeric_limits<std::int64_t>::min();
    case 2: return std::numeric_limits<std::int64_t>::max();
    case 3: return 1;
    case 4: return -1;
    default: return static_cast<std::int64_t>(rng.next() >> 1U);
  }
}

void rederive(EvidenceRecord& record) {
  record.provenance.body_digest = scp::Digest::of(
      std::span<const std::uint8_t>(record.body.data(), record.body.size()));
  const Result<scp::EvidenceId> identity = scp::derive_evidence_id(
      record.provenance, record.kind, record.schema_version, record.body);
  if (identity.has_value()) {
    record.id = identity.value();
  }
}

void corrupt_records(std::vector<EvidenceRecord>& records, SplitMix64& rng) {
  for (EvidenceRecord& record : records) {
    const std::uint64_t mutations = 1 + rng.below(3);
    for (std::uint64_t mutation = 0; mutation < mutations; ++mutation) {
      switch (rng.below(10)) {
        case 0:
          if (!record.body.empty()) {
            record.body[static_cast<std::size_t>(rng.below(record.body.size()))] ^= 0xFFU;
          }
          break;
        case 1:
          if (!record.body.empty()) {
            record.body[static_cast<std::size_t>(rng.below(record.body.size()))] ^= 0x01U;
            rederive(record);
          }
          break;
        case 2:
          switch (rng.below(5)) {
            case 0: record.schema_version = 0; break;
            case 1: record.schema_version = 2; break;
            case 2: record.schema_version = 999; break;
            case 3: record.schema_version = std::numeric_limits<std::uint16_t>::max(); break;
            default: break;
          }
          break;
        case 3:
          record.provenance.generation = scp::SourceGeneration(
              pick_extreme(rng, record.provenance.generation.value()));
          break;
        case 4:
          record.provenance.sequence = scp::Sequence(
              pick_extreme(rng, record.provenance.sequence.value()));
          break;
        case 5:
          record.provenance.epoch = scp::Epoch(pick_extreme(rng, record.provenance.epoch.value()));
          break;
        case 6:
          record.provenance.issued_at = Timestamp{pick_extreme_time(rng)};
          break;
        case 7:
          record.provenance.valid_until = Timestamp{pick_extreme_time(rng)};
          break;
        case 8:
          if (rng.below(4) == 0) {
            record.id = scp::EvidenceId{};
          } else {
            record.id = scp::EvidenceId(rng.next(), rng.next());
          }
          break;
        default:
          if (rng.coin()) {
            record.provenance.body_digest = scp::Digest{};
          } else {
            record.provenance.instance = scp::SourceInstanceId{};
          }
          break;
      }
    }
  }
}

