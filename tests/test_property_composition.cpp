SCP_TEST(order_independence_over_random_evidence_sets) {
  const Timestamp evaluation = scp_test::base_instant();
  const scp::SitePolicy policy = scp_test::strict_policy();
  std::size_t compared = 0;
  for (std::uint64_t scenario = 0; scenario < kScenarioCount; ++scenario) {
    const std::uint64_t seed = kMasterSeed + scenario * kSeedStride;
    SplitMix64 rng(seed);
    const std::vector<EvidenceRecord> records = random_evidence_set(rng, evaluation);
    const Result<SiteStateSnapshot> reference =
        scp::compose_site_state(records, options_for(evaluation, policy));
    if (!reference.has_value()) {
      check_scenario(false, "the reference composition succeeds", "compose reported " +
                       reference.status().to_string(), seed, records);
      continue;
    }
    bool reported = false;
    for (int permutation = 0; permutation < 5; ++permutation) {
      const std::vector<EvidenceRecord> permuted = shuffled_records(records, rng);
      const Result<SiteStateSnapshot> candidate =
          scp::compose_site_state(permuted, options_for(evaluation, policy));
      const bool permutation_matches_reference =
          candidate.has_value() &&
          candidate.value().snapshot_digest == reference.value().snapshot_digest;
      if (candidate.has_value()) {
        ++compared;
      }
      if (permutation_matches_reference) {
        SCP_CHECK(permutation_matches_reference);
        continue;
      }
      if (!reported) {
        reported = true;
        scp_test::Context::instance().note(
            "permutations of one evidence set composed to different snapshot digests. A tie at "
            "the greatest (epoch, generation, sequence) must be broken by content-addressed "
            "identity, so that no reported field of a resolution - not the accepted identity, not "
            "the digest, not an explanation string - can depend on which publication arrived "
            "first; tied keys:" +
            describe_tied_keys(records));
        check_scenario(false, "every permutation composes to the reference snapshot digest",
                       "first disagreeing permutation " + std::to_string(permutation), seed, records);
        continue;
      }
      check_scenario_brief(false, "every permutation composes to the reference snapshot digest",
                           "permutation " + std::to_string(permutation) + " also disagreed", seed);
    }
  }
  SCP_CHECK_EQ(compared, static_cast<std::size_t>(kScenarioCount) * 5);
}

