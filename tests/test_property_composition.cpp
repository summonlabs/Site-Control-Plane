SCP_TEST(a_newer_generation_never_yields_an_older_accepted_generation) {
  const Timestamp evaluation = scp_test::base_instant();
  const scp::SitePolicy policy = scp_test::strict_policy();
  for (std::uint64_t scenario = 0; scenario < kScenarioCount; ++scenario) {
    const std::uint64_t seed = kMasterSeed * 5ULL + scenario * kSeedStride;
    SplitMix64 rng(seed);
    const std::vector<EvidenceRecord> records = random_evidence_set(rng, evaluation);
    const Result<SiteStateSnapshot> before =
        scp::compose_site_state(records, options_for(evaluation, policy));
    if (!before.has_value()) {
      continue;
    }
    const EvidenceKind kind = static_cast<EvidenceKind>(1 + rng.below(scp::kEvidenceKindCount));
    const scp::EvidenceSlot slot{scp::owner_of(kind), kind};
    const SlotResolution* previous = before.value().find_slot(slot);
    const std::uint64_t previous_generation =
        previous == nullptr ? 0ULL : previous->accepted_generation.value();
    // An unresolved slot carries no epoch, and epoch zero is "not set" rather
    // than a statement about the publisher.
    const std::uint64_t previous_epoch =
        (previous == nullptr || previous->accepted_epoch.is_unset()) ? 1ULL
                                                                    : previous->accepted_epoch.value();
    if (previous_generation >= std::numeric_limits<std::uint64_t>::max() - 1ULL) {
      continue;
    }
    const std::uint64_t next_generation = previous_generation + 1ULL;
    const Result<EvidenceRecord> newer = random_record(kind, previous_epoch, next_generation, 1,
                                                       9, evaluation, Timestamp{},
                                                       scp::EvidenceOrigin::Ingested, rng);
    if (!newer.has_value()) {
      continue;
    }
    std::vector<EvidenceRecord> augmented = records;
    augmented.push_back(newer.value());
    const Result<SiteStateSnapshot> after =
        scp::compose_site_state(augmented, options_for(evaluation, policy));
    if (!after.has_value()) {
      check_scenario(false, "adding a newer generation still composes",
                     "compose reported " + after.status().to_string(), seed, augmented);
      continue;
    }
    const SlotResolution* resolution = after.value().find_slot(slot);
    const bool resolved = resolution != nullptr;
    check_scenario(resolved, "the slot is resolved after adding a newer generation",
                   "the slot disappeared", seed, augmented);
    if (!resolved) {
      continue;
    }
    check_scenario(resolution->accepted_generation.value() >= previous_generation,
                   "a strictly newer publication never lowers the accepted generation",
                   "previous=" + std::to_string(previous_generation) + " after=" +
                       std::to_string(resolution->accepted_generation.value()),
                   seed, augmented);
    check_scenario(resolution->accepted_id == newer.value().id,
                   "the newest publication is the accepted one for its slot",
                   "accepted=" + resolution->accepted_id.to_hex() + " expected=" +
                       newer.value().id.to_hex(),
                   seed, augmented);
  }
}

SCP_TEST(duplicating_records_never_changes_the_digest) {
  const Timestamp evaluation = scp_test::base_instant();
  const scp::SitePolicy policy = scp_test::strict_policy();
  bool first_failure = true;
  for (std::uint64_t scenario = 0; scenario < kScenarioCount; ++scenario) {
    const std::uint64_t seed = kMasterSeed * 7ULL + scenario * kSeedStride;
    SplitMix64 rng(seed);
    std::vector<EvidenceRecord> records = random_evidence_set(rng, evaluation);
    const Result<SiteStateSnapshot> reference =
        scp::compose_site_state(records, options_for(evaluation, policy));
    if (!reference.has_value() || records.empty()) {
      continue;
    }
    std::vector<EvidenceRecord> duplicated = records;
    const std::uint64_t copies = 1 + rng.below(5);
    for (std::uint64_t copy = 0; copy < copies; ++copy) {
      const std::size_t index = static_cast<std::size_t>(rng.below(records.size()));
      duplicated.push_back(records[index]);
    }
    const Result<SiteStateSnapshot> after =
        scp::compose_site_state(duplicated, options_for(evaluation, policy));
    const bool same = after.has_value() &&
                      after.value().snapshot_digest == reference.value().snapshot_digest;
    if (same) {
      SCP_CHECK(same);
      continue;
    }
    if (first_failure) {
      first_failure = false;
      scp_test::Context::instance().note(
          "one redundant copy of a record changed the snapshot digest. A duplicate is the same "
          "content-addressed identity, so it must be merged and counted without moving the digest "
          "of the composed picture: the digest describes what the site believes, not how many "
          "copies of a publication arrived.");
      check_scenario(false, "exact duplicates never change the snapshot digest",
                     std::to_string(copies) + " duplicate(s) changed the digest", seed, duplicated);
      continue;
    }
    check_scenario_brief(false, "exact duplicates never change the snapshot digest",
                         std::to_string(copies) + " duplicate(s) changed the digest", seed);
  }
}

SCP_TEST(hostile_input_never_crashes_and_never_fabricates_a_digest) {
  const Timestamp evaluation = scp_test::base_instant();
  const scp::SitePolicy policy = scp_test::strict_policy();
  std::size_t succeeded = 0;
  std::size_t refused = 0;
  for (std::uint64_t scenario = 0; scenario < kScenarioCount; ++scenario) {
    const std::uint64_t seed = kMasterSeed * 11ULL + scenario * kSeedStride;
    SplitMix64 rng(seed);
    std::vector<EvidenceRecord> records = random_evidence_set(rng, evaluation);
    if (records.empty()) {
      records.push_back(EvidenceRecord{});
    }
    corrupt_records(records, rng);
    const Result<SiteStateSnapshot> composed =
        scp::compose_site_state(records, options_for(evaluation, policy));
    if (!composed.has_value()) {
      ++refused;
      check_scenario(!composed.status().message().empty(),
                     "a refused composition carries a status message", "empty status message",
                     seed, records);
      continue;
    }
    ++succeeded;
    const SiteStateSnapshot& snapshot = composed.value();
    check_scenario(!snapshot.snapshot_digest.is_zero(),
                   "a composed snapshot never carries an unset digest", "zero snapshot digest",
                   seed, records);
    check_scenario(scp::compute_snapshot_digest(snapshot) == snapshot.snapshot_digest,
                   "the composed snapshot digest verifies",
                   "compute_snapshot_digest disagreed", seed, records);
    check_scenario(scp::compute_evidence_digest(snapshot.slots) == snapshot.evidence_digest,
                   "the composed evidence digest verifies",
                   "compute_evidence_digest disagreed", seed, records);
    const Result<SiteStateSnapshot> repeated =
        scp::compose_site_state(records, options_for(evaluation, policy));
    const bool deterministic = repeated.has_value() &&
                               repeated.value().snapshot_digest == snapshot.snapshot_digest;
    check_scenario(deterministic, "hostile input composes deterministically",
                   "a second composition differed", seed, records);
  }
  SCP_CHECK(succeeded > 0);
  SCP_CHECK_EQ(succeeded + refused, static_cast<std::size_t>(kScenarioCount));

  // The other branch of the property: the same hostile bytes under a policy
  // whose constraint bound is too small to describe them. Composition must
  // refuse with a status instead of composing a truncated picture.
  std::size_t tight_refusals = 0;
  scp::SitePolicy tight = scp_test::strict_policy();
  tight.max_constraints = 2;
  for (std::uint64_t scenario = 0; scenario < 32; ++scenario) {
    const std::uint64_t seed = kMasterSeed * 23ULL + scenario * kSeedStride;
    SplitMix64 rng(seed);
    std::vector<EvidenceRecord> records = random_evidence_set(rng, evaluation);
    corrupt_records(records, rng);
    const Result<SiteStateSnapshot> composed =
        scp::compose_site_state(records, options_for(evaluation, tight));
    if (!composed.has_value()) {
      ++tight_refusals;
      check_scenario(composed.status().code() == scp::StatusCode::LimitExceeded,
                     "a refused hostile composition reports why",
                     "compose reported " + composed.status().to_string(), seed, records);
      continue;
    }
    check_scenario(composed.value().constraints.size() <= tight.max_constraints,
                   "a successful composition respects the constraint bound",
                   "constraints=" + std::to_string(composed.value().constraints.size()), seed,
                   records);
  }
  SCP_CHECK(tight_refusals > 0);
}

