constexpr std::uint64_t kMasterSeed = 0x5C9E5EED0F0D1CE5ULL;
constexpr std::uint64_t kSeedStride = 0x9E3779B97F4A7C15ULL;
constexpr std::uint64_t kScenarioCount = 240;

/// Deterministic 64-bit generator (splitmix64). No std::random_device, no
/// wall-clock seeding, no std::rand.
class SplitMix64 {
 public:
  explicit SplitMix64(std::uint64_t seed) noexcept : state_(seed) {}

  std::uint64_t next() noexcept {
    state_ += 0x9E3779B97F4A7C15ULL;
    std::uint64_t value = state_;
    value = (value ^ (value >> 30U)) * 0xBF58476D1CE4E5B9ULL;
    value = (value ^ (value >> 27U)) * 0x94D049BB133111EBULL;
    return value ^ (value >> 31U);
  }

  std::uint64_t below(std::uint64_t bound) noexcept {
    return bound == 0 ? 0 : next() % bound;
  }

  bool coin() noexcept { return (next() & 1ULL) != 0ULL; }

 private:
  std::uint64_t state_;
};

std::string describe(const EvidenceRecord& record) {
  std::string text = std::string(scp::to_string(record.provenance.authority)) + "/" +
                     std::string(scp::to_string(record.kind)) +
                     " schema=" + std::to_string(record.schema_version) +
                     " epoch=" + std::to_string(record.provenance.epoch.value()) +
                     " generation=" + std::to_string(record.provenance.generation.value()) +
                     " sequence=" + std::to_string(record.provenance.sequence.value()) +
                     " instance=" + record.provenance.instance.to_hex() +
                     " issued=" + std::to_string(record.provenance.issued_at.nanos) +
                     " valid_until=" + std::to_string(record.provenance.valid_until.nanos) +
                     " origin=" + std::string(scp::to_string(record.origin)) +
                     " body=" + std::to_string(record.body.size()) + "B" +
                     " id=" + record.id.to_hex();
  return text;
}

/// Records a check; on failure it prints the seed and the whole evidence set, so
/// the case is reproducible from the printed output alone.
void check_scenario(bool condition, const char* expression, const std::string& context,
                    std::uint64_t seed, const std::vector<EvidenceRecord>& records) {
  if (condition) {
    scp_test::Context::instance().check(true, expression, __FILE__, __LINE__);
    return;
  }
  scp_test::Context::instance().note("seed=" + std::to_string(seed) + " (" +
                                     std::to_string(seed) + "ULL) " + context);
  scp_test::Context::instance().note("scenario carries " + std::to_string(records.size()) +
                                     " record(s):");
  for (const EvidenceRecord& record : records) {
    scp_test::Context::instance().note("  " + describe(record));
  }
  scp_test::Context::instance().check(false, expression, __FILE__, __LINE__);
}

/// Records a check with a one-line failure report. The scenario is still fully
/// reproducible from the printed seed because the generator is deterministic.
void check_scenario_brief(bool condition, const char* expression, const std::string& brief,
                          std::uint64_t seed) {
  if (condition) {
    scp_test::Context::instance().check(true, expression, __FILE__, __LINE__);
    return;
  }
  scp_test::Context::instance().note("seed=" + std::to_string(seed) + " " + brief);
  scp_test::Context::instance().check(false, expression, __FILE__, __LINE__);
}

/// Names every pair of publications that tie at one (authority, kind, epoch,
/// generation, sequence). Such a pair is what makes an arrival-ordered tie
/// resolution observable, so it is the first thing a failure report needs.
std::string describe_tied_keys(const std::vector<EvidenceRecord>& records) {
  std::string text;
  for (std::size_t first = 0; first < records.size(); ++first) {
    for (std::size_t second = first + 1; second < records.size(); ++second) {
      const EvidenceRecord& left = records[first];
      const EvidenceRecord& right = records[second];
      if (!(scp::slot_of(left) == scp::slot_of(right))) {
        continue;
      }
      if (!(left.provenance.epoch == right.provenance.epoch) ||
          !(left.provenance.generation == right.provenance.generation) ||
          !(left.provenance.sequence == right.provenance.sequence)) {
        continue;
      }
      text += " [" + std::string(scp::to_string(left.kind)) +
              " epoch=" + std::to_string(left.provenance.epoch.value()) +
              " generation=" + std::to_string(left.provenance.generation.value()) +
              " sequence=" + std::to_string(left.provenance.sequence.value()) +
              " ids=" + left.id.to_hex() + "/" + right.id.to_hex() +
              " distinct_instance=" + (left.provenance.instance == right.provenance.instance ? "no" : "yes") +
              " distinct_digest=" +
              (left.provenance.body_digest == right.provenance.body_digest ? "no" : "yes") + "]";
    }
  }
  return text.empty() ? std::string(" none") : text;
}

void append(std::vector<EvidenceRecord>& into, const std::vector<EvidenceRecord>& extra) {
  into.insert(into.end(), extra.begin(), extra.end());
}

