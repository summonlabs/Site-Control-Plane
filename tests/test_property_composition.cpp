/// \file test_property_composition.cpp
/// Seeded randomized properties of the composition engine.
///
/// Every scenario is generated by a splitmix64 generator from an explicit
/// constant, so any failure reproduces exactly: the seed and the full evidence
/// set are printed when a check fails. Nothing here reads a clock, the system
/// random device or an environment variable.

